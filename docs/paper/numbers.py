        add(macro(f"{k}DetR", n(s["detection"]["recall"]), src, f"systems.{k}.detection.recall"))
        add(macro(f"{k}DetFP", n(s["detection"]["falsePositives"]), src, f"systems.{k}.detection.falsePositives"))
