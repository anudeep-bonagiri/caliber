#!/usr/bin/env python3
"""Writes docs/paper/numbers.tex: every number in caliber.tex, as a LaTeX macro, read from the result files.

    python3 docs/paper/numbers.py [--baseline bench/BASELINE.json] [--out docs/paper/numbers.tex]

Sources (nothing else is allowed to put a number in the note):
  docs/FACTS.json                     the measured 92-day run (scripts/facts.py)
  bench/BASELINE.json                 the model-only baseline (bench/score.py)
  bench/carrierbench/REPORT.json      CarrierBench counts, controls, audit
  bench/carrierbench/oracle.json      the oracle ceiling
  bench/carrierbench/saboteur.json    the saboteur run
  spacetimedb/src/thresholds.ts       the kernel's limits
  context/PROJECT_STATUS.md           the one measured escalation latency (Task 26.3 beat)
  worker/src/config.ts                the Droid task timeout and concurrency defaults
  git                                 the two commits named in "what we got wrong", verified to exist

Also writes docs/paper/numbers_map.json: macro name, value, source file and the path or line it came from, which the
status entry's mapping table is generated from.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
CODES = ["location_mismatch", "capacity_exceeded", "rate_variance", "duplicate_toll", "duplicate_invoice",
         "vendor_bank_change", "short_received"]
# commits named in "what we got wrong"; the hash is an identifier, the script verifies it and reads its date and subject
COMMITS = {"commitLabelFix": "2fac596", "commitDecoyRerecord": "8e004e1"}

MAP: list[dict] = []


def tex(s: object) -> str:
    s = str(s)
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"), ("_", r"\_"),
                 ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}")):
        s = s.replace(a, b)
    return s


def n(x: object) -> str:
    if x is None:
        return "n/a"
    if isinstance(x, bool):
        return "yes" if x else "no"
    if isinstance(x, int):
        return f"{x:,}"
    if isinstance(x, float):
        return f"{x:.2f}"
    return tex(x)


def usd(cents: int) -> str:
    return f"\\${cents / 100:,.2f}"


def pct(x: float) -> str:
    return f"{x * 100:g}"


def macro(name: str, value: str, source: str, where: str, raw: object = None) -> str:
    MAP.append({"macro": name, "value": value, "source": source, "where": where, "raw": raw if raw is not None else value})
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def load(p: Path) -> dict:
    return json.loads(p.read_text())


def thresholds(path: Path) -> dict:
    src = path.read_text()
    out = {}
    for m in re.finditer(r"^\s*([A-Z_]+):\s*([0-9_.]+)n?,", src, re.M):
        out[m.group(1)] = float(m.group(2).replace("_", ""))
    return out


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, check=True, capture_output=True, text=True).stdout.strip()


