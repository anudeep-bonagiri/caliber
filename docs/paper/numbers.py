    add(macro("refusalsCount", n(F["refusals"]["count"]), src, "refusals.count"))
    add(macro("settleOffline", n(F["settlement"]["offlineIds"]), src, "settlement.offlineIds"))
    add(macro("settleLive", n(F["settlement"]["liveBankIds"]), src, "settlement.liveBankIds"))
