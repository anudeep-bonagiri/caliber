    add(macro("limitHoldsUsd", usd(F["limitHolds"]["cents"]), src, "limitHolds.cents"))
    add(macro("decoysCleared", n(F["decoysCleared"]), src, "decoysCleared"))
    add(macro("decoysOneAnswer", n(F["decoysClearedWithOneAnswer"]), src, "decoysClearedWithOneAnswer"))
    add(macro("plantedClearedByRule", n(len(F["plantedClearedByRule"])), src, "plantedClearedByRule (count)"))
