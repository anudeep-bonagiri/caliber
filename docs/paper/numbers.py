    add(macro("droidAvgSec", n(round(w["avg"]["durationMs"] / 1000, 1)), src, "worker_cost.perTask.avg.durationMs"))
    add(macro("droidCredits", n(w["total"]["factoryCredits"]), src, "worker_cost.perTask.total.factoryCredits"))
